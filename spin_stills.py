#!/usr/bin/env python3
"""spin_stills.py — render a gem-rotation still series with rustracer.

Each frame is ONE crisp still: the gem's static `spin` is set per render via
--spin <deg> (static placement, no motion blur; the camera/chart/env never
move).  N frames -> angular step 360/N degrees.

Usage:
    py spin_stills.py scenes/625469899.toml                 # 96 stills into scenes/625469899_spin/
    py spin_stills.py scenes/625469899.toml -n 48 -o out/spin
    py spin_stills.py scenes/625469899.toml --preset final --width 1280 --height 720
    py spin_stills.py scenes/625469899.toml --dry-run       # print commands only

Standard library only.  Afterwards, assemble with the printed ffmpeg command.
"""

import argparse
import os
import shutil
import subprocess


def main():
    ap = argparse.ArgumentParser(
        description="rustracer gem-spin still series (one crisp still per --spin angle)")
    ap.add_argument("scene", help="scene TOML (e.g. generated by report_to_toml.py)")
    ap.add_argument("-n", "--frames", type=int, default=96,
                    help="number of stills (default 96; angle step = 360/N)")
    ap.add_argument("-o", "--output", default=None,
                    help="output directory (default: <scene>_spin/)")
    ap.add_argument("--preset", default="final", help="render preset: preview|final (default: final)")
    ap.add_argument("--width", type=int, default=1280)
    ap.add_argument("--height", type=int, default=720)
    ap.add_argument("--samples", type=int, default=None, help="override spp")
    ap.add_argument("--exe", default=None,
                    help="rustracer binary (default: target/release/rustracer.exe)")
    ap.add_argument("--denoise", action="store_true", help="pass --denoise to each render")
    ap.add_argument("--dry-run", action="store_true", help="print the commands without running")
    args = ap.parse_args()

    if not os.path.exists(args.scene):
        raise SystemExit("error: %s not found" % args.scene)
    exe = args.exe or os.path.join("target", "release", "rustracer.exe")
    out = args.output or (os.path.splitext(args.scene)[0] + "_spin")
    os.makedirs(out, exist_ok=True)

    n = args.frames
    step = 360.0 / n
    cmds = []
    for i in range(n):
        png = os.path.join(out, "gem_%04d.png" % i)
        cmd = [exe, "--render", "--scene", args.scene, "--spin", "%.6f" % (i * step),
               "--preset", args.preset, "--width", str(args.width), "--height", str(args.height),
               "--frames", "1", "--output", png]
        if args.samples:
            cmd += ["--samples", str(args.samples)]
        if args.denoise:
            cmd.append("--denoise")
        cmds.append(cmd)

    if args.dry_run:
        for c in cmds:
            print(" ".join(c))
        return

    for i, cmd in enumerate(cmds):
        print("[%d/%d] spin=%9.4f deg -> %s" % (i + 1, n, i * step, os.path.basename(cmd[-1])))
        r = subprocess.run(cmd)
        if r.returncode != 0:
            raise SystemExit("render failed at frame %d (exit %d)" % (i, r.returncode))

    print("\nAll %d stills saved to %s/" % (n, out))
    print("Assemble with ffmpeg:")
    print('  ffmpeg -r 24 -i "%s" -c:v libx264 -pix_fmt yuv420p output.mp4'
          % os.path.join(out, "gem_%04d.png").replace(os.sep, "/"))


if __name__ == "__main__":
    main()
